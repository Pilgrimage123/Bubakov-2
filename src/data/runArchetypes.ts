export function selectRunRozmar(levelId: GameLevelId, seed?: number): RunRozmarDef {
  const options = RUN_ROZMARY[levelId] || RUN_ROZMARY[1];
  const s = typeof seed === 'number' ? Math.abs(Math.floor(seed)) : Math.floor(Math.random() * 1000000);
  const index = s % options.length;
  return options[index];
}
